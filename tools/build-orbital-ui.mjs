import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url),read=async p=>JSON.parse(await readFile(new URL(p,root),'utf8'));
const orbital=await read('content/orbital-ui.json'),portfolio=await read('content/translations/es.json'),invariants=await read('content/translations/invariants.json');
export const catalog={strings:{...portfolio,...orbital.strings},patterns:orbital.patterns,invariants:[...new Set([...invariants.filter(s=>!['AI','TH'].includes(s)),...orbital.invariants])]};
for(const [key,value] of Object.entries({...catalog.strings,...catalog.patterns})){
 if(!value||typeof value!=='string')throw Error('Empty Orbital translation: '+key);
 const parameters=s=>[...s.matchAll(/\{(\w+)\}/g)].map(m=>m[1]).sort().join(',');
 if(parameters(key)!==parameters(value))throw Error('Mismatched translation parameters: '+key);
}
await writeFile(new URL('scripts/lab/locale-data.js',root),'// Generated by tools/build-orbital-ui.mjs. Edit content/orbital-ui.json.\nexport const catalog='+JSON.stringify(catalog)+';\n');
